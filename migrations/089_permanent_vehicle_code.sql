-- Vehicle identity is permanent; existing assignment history is retained.
ALTER TABLE vehicles ADD COLUMN joining_code VARCHAR(20);
UPDATE vehicles v SET joining_code=(
 SELECT d.code FROM driver_assignment_codes d
 WHERE d.vehicle_id=v.id
 ORDER BY CASE
  WHEN d.status='CLAIMED' AND d.driver_id=(SELECT user_id FROM driver_profiles WHERE id=v.driver_profile_id) THEN 0
  WHEN d.status='ACTIVE' THEN 1 WHEN d.status='CLAIMED' THEN 2 ELSE 3 END,
  d.created_at DESC,d.id DESC LIMIT 1
);
CREATE UNIQUE INDEX vehicles_joining_code_uidx ON vehicles(joining_code);
CREATE FUNCTION preserve_vehicle_joining_code() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE candidate TEXT;
BEGIN
 IF TG_OP='UPDATE' AND OLD.joining_code IS NOT NULL THEN
  IF NEW.joining_code IS DISTINCT FROM OLD.joining_code THEN
   RAISE EXCEPTION 'Vehicle code is permanent' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 IF NEW.joining_code IS NOT NULL THEN
  RAISE EXCEPTION 'Vehicle codes are generated by the database' USING ERRCODE='23514';
 END IF;
 FOR attempt IN 1..100 LOOP
  candidate=lpad(floor(random()*1000000)::text,6,'0');
  PERFORM pg_advisory_xact_lock(hashtextextended('vehicle_code:'||candidate,0));
  IF NOT EXISTS(SELECT 1 FROM vehicles WHERE joining_code=candidate)
     AND NOT EXISTS(SELECT 1 FROM driver_assignment_codes WHERE code=candidate) THEN
   NEW.joining_code=candidate; RETURN NEW;
  END IF;
 END LOOP;
 RAISE EXCEPTION 'Vehicle code capacity exceeded';
END $$;
CREATE TRIGGER vehicles_permanent_joining_code BEFORE INSERT OR UPDATE OF joining_code ON vehicles
 FOR EACH ROW EXECUTE FUNCTION preserve_vehicle_joining_code();
UPDATE vehicles SET joining_code=NULL WHERE joining_code IS NULL;
ALTER TABLE vehicles ALTER COLUMN joining_code SET NOT NULL;
